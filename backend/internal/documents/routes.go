package documents

import "github.com/gofiber/fiber/v2"

func RegisterRoutes(router fiber.Router, handler *Handler) {
	group := router.Group("/documents")
	group.Get("", handler.List)
	group.Get("/", handler.List)
	group.Get("/trash", handler.ListDeleted)
	group.Get("/favorites", handler.ListFavorites)
	group.Get("/search", handler.Search)
	group.Get("/hybrid-search", handler.HybridSearch)
	group.Get("/semantic-search", handler.SemanticSearch)
	group.Get("/by-tag/:tagId", handler.ListByTag)
	group.Post("/upload", handler.Upload)
	group.Post("/:id/restore", handler.Restore)
	group.Post("/:id/reprocess-text", handler.ReprocessText)
	group.Post("/:id/tags", handler.SetDocumentTags)
	group.Get("/:id/versions", handler.ListVersions)
	group.Post("/:id/versions", handler.UploadVersion)
	group.Post("/:id/versions/:versionId/restore", handler.RestoreVersion)
	group.Get("/:id/comments", handler.ListComments)
	group.Post("/:id/comments", handler.CreateComment)
	group.Put("/:id/comments/:commentId", handler.UpdateComment)
	group.Delete("/:id/comments/:commentId", handler.DeleteComment)
	group.Get("/:id/important-dates", handler.ListImportantDates)
	group.Get("/:id/important-dates/suggestions", handler.ListImportantDateSuggestions)
	group.Post("/:id/important-dates/extract-ai", handler.ExtractAIImportantDates)
	group.Post("/:id/important-dates/suggestions/:suggestionId/accept", handler.AcceptImportantDateSuggestion)
	group.Post("/:id/important-dates/suggestions/:suggestionId/reject", handler.RejectImportantDateSuggestion)
	group.Post("/:id/important-dates", handler.CreateImportantDate)
	group.Put("/:id/important-dates/:dateId", handler.UpdateImportantDate)
	group.Delete("/:id/important-dates/:dateId", handler.DeleteImportantDate)
	group.Patch("/:id/important-dates/:dateId/complete", handler.CompleteImportantDate)
	group.Delete("/:id/permanent", handler.PermanentlyDelete)
	group.Get("/:id/text", handler.GetText)
	group.Get("/:id/chunks", handler.GetChunks)
	group.Get("/:id/chunk-stats", handler.GetChunkStats)
	group.Get("/:id/file", handler.GetFile)
	group.Get("/:id/workspace", handler.GetWorkspace)
	group.Get("/:id/summary", handler.GetSummary)
	group.Post("/:id/summary/generate", handler.GenerateSummary)
	group.Get("/:id/ai-progress", handler.GetAIProgress)
	group.Get("/:id/ai-metadata", handler.GetAIMetadata)
	group.Post("/:id/ai-metadata/generate", handler.GenerateAIMetadata)
	group.Get("/:id/classification", handler.GetDocumentClassification)
	group.Post("/:id/classification/generate", handler.GenerateDocumentClassification)
	group.Get("/:id/suggested-tags", handler.GetSuggestedTags)
	group.Post("/:id/suggested-tags/accept-all", handler.AcceptAllSuggestedTags)
	group.Post("/:id/suggested-tags/:suggestedTagId/accept", handler.AcceptSuggestedTag)
	group.Post("/:id/suggested-tags/:suggestedTagId/reject", handler.RejectSuggestedTag)
	group.Get("/:id/entities", handler.ListDocumentEntities)
	group.Post("/:id/entities/extract-ai", handler.ExtractAIDocumentEntities)
	group.Delete("/:id/entities/:entityId", handler.DeleteDocumentEntity)
	group.Get("/:id/related-suggestions", handler.ListRelatedSuggestions)
	group.Post("/:id/related-suggestions/generate", handler.GenerateRelatedSuggestions)
	group.Post("/:id/related-suggestions/:suggestionId/accept", handler.AcceptRelatedSuggestion)
	group.Post("/:id/related-suggestions/:suggestionId/reject", handler.RejectRelatedSuggestion)
	group.Get("/:id/relationships", handler.ListRelationships)
	group.Post("/:id/relationships", handler.CreateRelationship)
	group.Post("/:id/lock", handler.LockDocument)
	group.Post("/:id/unlock", handler.UnlockDocument)
	group.Get("/:id/health", handler.GetDocumentHealth)
	group.Get("/:id", handler.GetByID)
	group.Patch("/:id", handler.Update)
	group.Patch("/:id/favorite", handler.Favorite)
	group.Patch("/:id/unfavorite", handler.Unfavorite)
	group.Put("/:id", handler.Update)
	group.Delete("/:id", handler.Delete)
}

func RegisterImportantDateRoutes(router fiber.Router, handler *Handler) {
	router.Get("/important-dates", handler.ListImportantDatesGlobal)
}

func RegisterRelationshipRoutes(router fiber.Router, handler *Handler) {
	router.Delete("/document-relationships/:id", handler.DeleteRelationship)
}
